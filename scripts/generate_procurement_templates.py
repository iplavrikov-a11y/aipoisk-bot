"""Generate neutral public learning templates for comparing commercial proposals."""
from __future__ import annotations

import csv
from pathlib import Path

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Pt


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "site" / "public" / "materialy"


def write_request_template() -> None:
    document = Document()
    document.core_properties.title = "Шаблон запроса коммерческого предложения"
    title = document.add_heading("Шаблон запроса коммерческого предложения", 0)
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    document.add_paragraph("Учебный бланк для сбора сопоставимых предложений. Заполните поля в квадратных скобках и приложите спецификацию.")
    document.add_heading("Кому", level=1)
    document.add_paragraph("[Наименование поставщика]\n[Контакт отдела продаж]\n[Электронная почта]")
    document.add_heading("Запрос", level=1)
    document.add_paragraph(
        "Просим предоставить коммерческое предложение на [наименование товара / работ / услуг] по приложенной спецификации. "
        "Укажите, пожалуйста, условия по каждой позиции отдельно и дату, на которую предложение действительно."
    )
    document.add_heading("Что просим указать в ответе", level=1)
    for item in [
        "Наименование, модель, производитель, артикул и ссылка на технический документ.",
        "Соответствие каждому параметру ТЗ; отдельно — расхождения, варианты и неподтвержденные параметры.",
        "Количество, комплектность, единицу измерения и готовность комплекта к поставке.",
        "Цену с указанием НДС, доставки, разгрузки, тары и иных включенных или исключенных расходов.",
        "Место и срок поставки, условия оплаты, срок действия предложения и гарантийные условия.",
        "Дату ответа, реквизиты и контакт сотрудника, который может подтвердить предложение.",
    ]:
        document.add_paragraph(item, style="List Bullet")
    document.add_heading("Исходные условия", level=1)
    table = document.add_table(rows=0, cols=2)
    table.style = "Table Grid"
    for label in ["Позиция / спецификация", "Количество", "Адрес поставки", "Желаемый период поставки", "Условия оплаты", "Контакт для ответа"]:
        cells = table.add_row().cells
        cells[0].text = label
        cells[1].text = "[заполнить]"
    document.add_paragraph("Этот запрос предназначен для получения информации и сам по себе не является заказом, офертой или обязательством заключить договор.")
    style = document.styles["Normal"]
    style.font.name = "Arial"
    style.font.size = Pt(10)
    document.save(OUTPUT / "shablon-zaprosa-kp.docx")


