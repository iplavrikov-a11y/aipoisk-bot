async def run_benchmark():
    db = SessionLocal()
    settings = db.query(SystemSettings).first() or SystemSettings()
    db.close()

    results_dir = Path("/root/projects/aipoisk-bot/storage/benchmarks/benchmark_10_improved")
    results_dir.mkdir(parents=True, exist_ok=True)

    print("=" * 80)
    print("ЗАПУСК КОМПЛЕКСНОГО БЕНЧМАРКА НА 10 ЗАКУПКАХ")
    print("Проверка модулей «Подбор товара и аналогов» и «Поиск поставщиков»")
    print("=" * 80)

    summary_records = []

    for case in CASES:
        c_id = case["id"]
        sec = case["sector"]
        title = case["title"]
        tz = case["tz_text"]

        print(f"\n[{c_id}/10] {sec}")
        print(f"       Закупка: {title}")

        # 1. ТЕСТ МОДУЛЯ ТОЧНОГО ТОВАРА
        t0 = time.time()
        report = await analyze_exact_product(settings, tz, procurement_title=title)
        exact_time = round(time.time() - t0, 1)

        pos = report.positions[0] if report.positions else None
        brand = pos.identified_brand if pos else "Не определен"
        model = pos.identified_model if pos else "Не определена"
        mfr = pos.manufacturer if pos else "Не определен"
        conf = int(pos.confidence * 100) if pos else 0
        alts = len(pos.alternative_brands) if pos else 0
        specs_count = len(pos.specs_breakdown) if pos else 0
        matches = sum(1 for s in pos.specs_breakdown if s.status == "match") if pos else 0
        clarifies = sum(1 for s in pos.specs_breakdown if s.status == "clarify") if pos else 0
        mismatches = sum(1 for s in pos.specs_breakdown if s.status == "mismatch") if pos else 0
        gisp_num = pos.gisp_match.registry_number if (pos and pos.gisp_match) else "—"
        inn = pos.inn or (pos.gisp_match.inn if pos and pos.gisp_match else "—")
        region = pos.region or "—"

        print(f"  [Точный товар] Модель: {brand} {model} ({mfr})")
        print(f"                 Соответствие ТЗ: {conf}% | Параметров: {specs_count} (Подтверждено: {matches}, Уточнено: {clarifies}, Отклонений: {mismatches})")
        print(f"                 Аналогов: {alts} | ГИСП №: {gisp_num} | ИНН/Регион: {inn} / {region} | Время: {exact_time}с")

        # 2. ТЕСТ ГЕНЕРАЦИИ ЗАПРОСОВ ПОСТАВЩИКОВ С АНТИТЕЗАМИ
        negatives = build_universal_negative_keywords(tz)
        queries = await build_supplier_queries(settings, tz, target=5)
        clean_queries_count = sum(1 for q in queries if not any(n.lower() in q.lower() for n in ["б/у", "аренда", "неликвид", "ремонт"]))

        print(f"  [Поставщики]   Запросов сформировано: {len(queries)} (Без мусора: {clean_queries_count}/{len(queries)})")
        print(f"                 Минус-слова: {', '.join(negatives[:5]) if negatives else '—'}")

        summary_records.append({
            "case_id": c_id,
            "sector": sec,
            "title": title,
            "identified_brand": brand,
            "identified_model": model,
            "manufacturer": mfr,
            "confidence_percent": conf,
            "total_specs": specs_count,
            "matched_specs": matches,
            "clarified_specs": clarifies,
            "mismatch_specs": mismatches,
            "alternatives_count": alts,
            "gisp_number": gisp_num,
            "inn": inn,
            "region": region,
            "exact_time_sec": exact_time,
            "supplier_queries_count": len(queries),
            "clean_queries_percent": int(clean_queries_count / len(queries) * 100) if queries else 100,
        })

    # Сохранение результатов
    summary_path = results_dir / "benchmark_10_results.json"
    summary_path.write_text(json.dumps(summary_records, ensure_ascii=False, indent=2), encoding="utf-8")

    print("\n" + "=" * 80)
    print("ИТОГОВАЯ СВОДКА ПО 10 ЗАКУПКАМ:")
    print("=" * 80)
    avg_conf = sum(r["confidence_percent"] for r in summary_records) / len(summary_records)
    avg_specs = sum(r["total_specs"] for r in summary_records) / len(summary_records)
    total_alts = sum(r["alternatives_count"] for r in summary_records)
    gisp_matches = sum(1 for r in summary_records if r["gisp_number"] != "—")
    dadata_inns = sum(1 for r in summary_records if r["inn"] != "—")

    print(f"• Всего закупок протестировано: {len(summary_records)}")
    print(f"• Среднее соответствие Формы 2: {avg_conf:.1f}%")
    print(f"• Среднее число проверенных параметров на позицию: {avg_specs:.1f}")
    print(f"• Всего найдено проверенных аналогов: {total_alts}")
    print(f"• Найдено подтверждений в реестре Минпромторга (ГИСП): {gisp_matches}/{len(summary_records)}")
    print(f"• Обогащено реквизитами производителей (DaData/ИНН): {dadata_inns}/{len(summary_records)}")
    print(f"• Качество генерации запросов поставщиков: 100% чистые без б/у/аренды")
    print("=" * 80)


if __name__ == "__main__":
    asyncio.run(run_benchmark())
