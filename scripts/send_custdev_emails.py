def get_smtp_connection():
    con = sqlite3.connect('/root/projects/tenderlex/data/aipoisk.db')
    cur = con.cursor()
    row = cur.execute('SELECT smtp_host, smtp_port, smtp_user, smtp_password FROM outreach_settings WHERE id=1').fetchone()
    host, port, user, pwd = row

    s = socks.socksocket()
    s.set_proxy(socks.SOCKS5, '127.0.0.1', 1080)
    s.settimeout(20)
    s.connect((host, port))

    ctx = ssl.create_default_context()
    ss = ctx.wrap_socket(s, server_hostname=host)
    smtp = smtplib.SMTP_SSL()
    smtp.sock = ss
    smtp.file = ss.makefile('rb')
    smtp.getreply()
    smtp.login(user, pwd)
    return smtp, user

def send_single_email(smtp, from_user, to_email, subject, body_text):
    msg = EmailMessage()
    msg['From'] = formataddr(('Алексей', from_user))
    msg['To'] = to_email
    msg['Reply-To'] = from_user
    msg['Subject'] = subject
    msg.set_content(body_text)
    smtp.send_message(msg)

if __name__ == '__main__':
    dry_run = '--send' not in sys.argv
    print(f"=== CustDev Email Dispatcher (Mode: {'DRY RUN' if dry_run else 'LIVE SEND'}) ===")
    
    if dry_run:
        print(f"Loaded {len(EMAILS_GROUP_B)} targeted letters for Group B:")
        for i, item in enumerate(EMAILS_GROUP_B, 1):
            print(f"{i}. TO: {item['to_name']} <{item['to_email']}> | SUBJ: {item['subject']}")
        print("\nTo send real emails, run: python3 send_custdev_emails.py --send")
        sys.exit(0)

    print("Connecting to SMTP via SOCKS5 proxy...")
    smtp, from_user = get_smtp_connection()
    print(f"Connected as {from_user}. Starting dispatch...")

    for i, item in enumerate(EMAILS_GROUP_B, 1):
        print(f"[{i}/{len(EMAILS_GROUP_B)}] Sending to {item['to_name']} ({item['to_email']})...", end='', flush=True)
        try:
            send_single_email(smtp, from_user, item['to_email'], item['subject'], item['body'])
            print(" OK")
        except Exception as e:
            print(f" FAILED: {e}")
        time.sleep(3)

    smtp.close()
    print("All emails processed successfully.")
