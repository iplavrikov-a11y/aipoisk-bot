async def run_single_test(case: dict, settings: SystemSettings, out_dir: Path):
    case_id = case["id"]
    category = case["category"]
    title = case["title"]
    tz_text = case["text"]

    t0 = time.perf_counter()
    report: ExactProductReport = await analyze_exact_product(
        settings,
        tz_text,
        procurement_title=title,
    )
    dt = time.perf_counter() - t0

    # Write DOCX and XLSX
    docx_file = out_dir / f"Форма_2_{case_id}_{category.replace(' ', '_')}.docx"
    xlsx_file = out_dir / f"Аналоги_{case_id}_{category.replace(' ', '_')}.xlsx"
    write_exact_product_docx(docx_file, report, title=f"Форма 2: {title}")
    write_exact_product_xlsx(xlsx_file, report, title=f"Сверка характеристик: {title}")

    # Metrics calculation
    pos = report.positions[0] if report.positions else None
    specs = pos.specs_breakdown if pos else []
    total_specs = len(specs)
    matched_specs = [s for s in specs if s.status == "match"]
    clarify_specs = [s for s in specs if s.status == "clarify"]
    mismatch_specs = [s for s in specs if s.status == "mismatch"]

    # Check for hallucinations / synthetic TZ copying
    hallucinated_count = 0
    for s in specs:
        # If product_fact literally copies non-trivial requirement range without source while marked match
        if ("не менее" in s.tz_requirement or "не более" in s.tz_requirement or "от " in s.tz_requirement):
            if s.product_fact == s.tz_requirement:
                hallucinated_count += 1

    alternatives = pos.alternative_brands if pos else []
    alt_names = [f"{a.brand} {a.model}" for a in alternatives]

    result = {
        "id": case_id,
        "category": category,
        "title": title,
        "elapsed_sec": round(dt, 2),
        "identified_brand": pos.identified_brand if pos else "N/A",
        "identified_model": pos.identified_model if pos else "N/A",
        "manufacturer": pos.manufacturer if pos else "N/A",
        "confidence": pos.confidence if pos else 0.0,
        "gisp_registry": pos.gisp_match.registry_number if (pos and pos.gisp_match) else "—",
        "total_specs": total_specs,
        "matched_count": len(matched_specs),
        "clarify_count": len(clarify_specs),
        "mismatch_count": len(mismatch_specs),
        "coverage_percent": round((len(matched_specs) / total_specs * 100) if total_specs else 0, 1),
        "web_sources_count": len(report.web_sources),
        "verified_docs_count": len(report.verified_documents),
        "pdf_docs_count": len([d for d in report.verified_documents if d.get("type") == "pdf"]),
        "html_docs_count": len([d for d in report.verified_documents if d.get("type") == "html"]),
        "alternatives_count": len(alternatives),
        "alternatives": alt_names,
        "hallucinations_detected": hallucinated_count,
        "docx_size_bytes": docx_file.stat().st_size if docx_file.exists() else 0,
        "xlsx_size_bytes": xlsx_file.stat().st_size if xlsx_file.exists() else 0,
        "sample_specs": [
            {
                "param": s.param_name,
                "tz": s.tz_requirement,
                "fact": s.product_fact,
                "status": s.status,
                "comment": s.comment,
            }
            for s in specs[:4]
        ],
    }
    return result


