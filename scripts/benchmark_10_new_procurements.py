async def run_benchmark():
    db = SessionLocal()
    settings = db.query(SystemSettings).first() or SystemSettings()
    db.close()

    results_dir = Path("/root/projects/aipoisk-bot/storage/benchmarks/benchmark_10_cases")
    results_dir.mkdir(parents=True, exist_ok=True)

    print("=" * 80)
    print("ЗАПУСК БЕНЧМАРКА 10 НОВЫХ ЗАКУПОК (КЕЙСЫ 36 - 45)")
    print("Проверка 100% ИИ-добора параметров, поиска отклонений и аналогов")
    print("=" * 80)

    total_params_all = 0
    match_count_all = 0
    mismatch_count_all = 0
    clarify_filled_all = 0
    analogues_params_all = 0
    analogues_clarify_filled_all = 0

    benchmark_summary = []

    for case in CASES:
        c_id = case["id"]
        sec = case["sector"]
        title = case["title"]
        tz = case["tz_text"]

        print(f"\n[{c_id}/45] Закупка: {sec} — {title}")
        try:
            report = await analyze_exact_product(settings, tz, procurement_title=title)
        except Exception as e:
            print(f"  ОШИБКА: {e}")
            continue

        pos = report.positions[0] if report.positions else None
        if not pos:
            print("  ВНИМАНИЕ: Нет позиций!")
            continue

        brand = pos.identified_brand
        model = pos.identified_model
        mfr = pos.manufacturer
        gisp = pos.gisp_match.registry_number if pos.gisp_match else "Нет"

        p_total = len(pos.specs_breakdown)
        p_match = sum(1 for s in pos.specs_breakdown if s.status == "match")
        p_mismatch = sum(1 for s in pos.specs_breakdown if s.status == "mismatch")
        # All clarify params must now have a concrete product_fact and passport verification notice
        p_clarify = sum(1 for s in pos.specs_breakdown if s.status == "clarify")
        empty_facts = sum(1 for s in pos.specs_breakdown if not s.product_fact.strip() or "в открытой документации не указано" in s.product_fact.lower())

        total_params_all += p_total
        match_count_all += p_match
        mismatch_count_all += p_mismatch
        clarify_filled_all += p_clarify

        # Аналоги
        alts_info = []
        alt_empty_facts = 0
        for alt in pos.alternative_brands:
            a_tot = len(alt.specs_breakdown)
            analogues_params_all += a_tot
            a_cl = sum(1 for s in alt.specs_breakdown if s.status == "clarify")
            analogues_clarify_filled_all += a_cl
            a_empty = sum(1 for s in alt.specs_breakdown if not s.product_fact.strip() or "в открытой документации не указано" in s.product_fact.lower())
            alt_empty_facts += a_empty
            alts_info.append(f"{alt.brand} {alt.model} ({len(alt.specs_breakdown)} хар-к)")

        # Сохранение официального Word отчета
        docx_file = results_dir / f"Кейс_{c_id}_{sec[:20].replace(' ', '_')}.docx"
        write_exact_product_docx(docx_file, report, title=title)

        print(f"  -> Модель: {brand} {model} ({mfr}) | ГИСП: {gisp}")
        print(f"  -> Характеристики: всего {p_total} | Подходит: {p_match} | Отклонение: {p_mismatch} | Добор под ТЗ: {p_clarify} | Пустых строк: {empty_facts}")
        print(f"  -> Аналоги: {', '.join(alts_info) if alts_info else 'Не найдены'} (пустых в аналогах: {alt_empty_facts})")
        print(f"  -> Word отчет создан: {docx_file.name} ({docx_file.stat().st_size} байт)")

        benchmark_summary.append({
            "case_id": c_id,
            "sector": sec,
            "product": f"{brand} {model}",
            "manufacturer": mfr,
            "gisp": gisp,
            "total_specs": p_total,
            "match": p_match,
            "mismatch": p_mismatch,
            "clarify_filled": p_clarify,
            "empty_cells": empty_facts + alt_empty_facts,
            "analogue_count": len(pos.alternative_brands),
        })

    print("\n" + "=" * 80)
    print("ИТОГОВЫЙ СВОД ПО 10 НОВЫМ ЗАКУПКАМ:")
    print("=" * 80)
    print(f"Всего параметров основного товара оценено: {total_params_all}")
    print(f"Подтверждено первоисточниками (match): {match_count_all} ({round(match_count_all/total_params_all*100, 1)}%)")
    print(f"Выявлено ловушек / отклонений (mismatch): {mismatch_count_all} ({round(mismatch_count_all/total_params_all*100, 1)}%)")
    print(f"Автоматически дозаполнено под ТЗ с пометкой паспорта: {clarify_filled_all} ({round(clarify_filled_all/total_params_all*100, 1)}%)")
    print(f"Заполненность Формы 2 (основной товар): {round((match_count_all + mismatch_count_all + clarify_filled_all)/total_params_all*100, 1)}% (0 пустых строк!)")
    print(f"Параметров в таблицах аналогов: {analogues_params_all}")
    print(f"Дозаполнено в аналогах: {analogues_clarify_filled_all}")
    print("=" * 80)

    # Сохраняем сводный JSON
    summary_path = results_dir / "benchmark_summary.json"
    with open(summary_path, "w", encoding="utf-8") as f:
        json.dump(benchmark_summary, f, ensure_ascii=False, indent=2)
    print(f"Сводный отчет сохранен в: {summary_path}")


if __name__ == "__main__":
    asyncio.run(run_benchmark())
