export function getKnowledgeArticleBySlug(
  slug: string
): KnowledgeArticleMeta | undefined {
  const cleanSlug = slug.replace(/^\/baza-znaniy\//, "").replace(/^\//, "");
  return KNOWLEDGE_ARTICLES.find((a) => a.slug === cleanSlug);
}

export function getRelatedArticles(
  slug: string,
  limit: number = 3
): KnowledgeArticleMeta[] {
  const current = getKnowledgeArticleBySlug(slug);
  if (!current) return KNOWLEDGE_ARTICLES.slice(0, limit);

  if (current.relatedSlugs && current.relatedSlugs.length > 0) {
    const fromSlugs = current.relatedSlugs
      .map((s) => getKnowledgeArticleBySlug(s))
      .filter((a): a is KnowledgeArticleMeta => Boolean(a));
    if (fromSlugs.length >= limit) return fromSlugs.slice(0, limit);
  }

  const sameCategory = KNOWLEDGE_ARTICLES.filter(
    (a) => a.slug !== current.slug && a.category === current.category
  );
  const otherCategory = KNOWLEDGE_ARTICLES.filter(
    (a) => a.slug !== current.slug && a.category !== current.category
  );

  return [...sameCategory, ...otherCategory].slice(0, limit);
}
