async def run_single_test(case: dict, settings: SystemSettings, out_dir: Path) -> dict:
    cid = case["id"]
    cat = case["category"]
    title = case["title"]
    text = case["text"]
    print(f"\n[Case {cid}/35] Запуск теста: {cat} — {title}")
    t0 = time.perf_counter()

    report: ExactProductReport = await analyze_exact_product(
        settings,
        text,
        procurement_title=title,
    )
    elapsed = round(time.perf_counter() - t0, 2)

    total_specs = 0
    matched = 0
    clarify = 0
    mismatch = 0
    brand = ""
    model = ""
    manufacturer = ""
    conf = 0.0
    gisp = "—"
    sample_specs = []

    pos = report.positions[0] if report.positions else None
    specs = pos.specs_breakdown if pos else []
    total_specs = len(specs)
    matched_specs = [s for s in specs if s.status == "match"]
    clarify_specs = [s for s in specs if s.status == "clarify"]
    mismatch_specs = [s for s in specs if s.status == "mismatch"]

    if pos:
        brand = pos.identified_brand
        model = pos.identified_model
        manufacturer = pos.manufacturer
        conf = pos.confidence
        gisp = pos.gisp_match.registry_number if pos.gisp_match else "—"

    cov = round((len(matched_specs) / total_specs * 100) if total_specs else 0, 1)
    det_rate = round(((len(matched_specs) + len(mismatch_specs)) / total_specs * 100) if total_specs else 0, 1)

    print(f"  -> Бренд/Модель: {brand} {model} ({manufacturer}) [GISP: {gisp}]")
    print(f"  -> Итого параметров: {total_specs}, Подтверждено: {len(matched_specs)} ({cov}%), Mismatch: {len(mismatch_specs)}, Clarify: {len(clarify_specs)}. Всего определено: {det_rate}%")
