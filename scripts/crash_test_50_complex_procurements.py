def evaluate_case(spec: dict, profile: ProcurementProfile) -> dict:
    """Evaluate extracted profile against the spec rules."""
    items = profile.items
    num_items = len(items)

    # Check 1: Did we get non-zero items?
    if num_items == 0:
        return {
            "case_id": spec["id"],
            "title": spec["title"],
            "score": 0.0,
            "pass": False,
            "reasons": ["Профиль пуст (0 позиций)"],
            "items": [],
        }

    reasons_penalty = []
    reasons_praise = []
    score = 10.0

    # 1. Check Core vs Auxiliary
    core_items = [it for it in items if it.is_core]
    aux_items = [it for it in items if it.is_auxiliary]

    if not core_items:
        score -= 3.0
        reasons_penalty.append("Нет ни одной основной позиции (is_core=true)")

    # 2. Check Hardware Absorption
    # If the spec specifies hardware to absorb, verify they didn't become isolated standalone expensive categories
    spec_hw = [hw.lower() for hw in spec.get("hardware_to_absorb", [])]
    for it in items:
        name_l = it.name.lower()
        for hw in spec_hw:
            # If item is solely named after minor hardware AND marked as core
            if hw in name_l and len(name_l.split()) <= 3 and it.is_core and len(it.included_sub_items) <= 1:
                score -= 1.5
                reasons_penalty.append(f"Изолированная категория крепежа: «{it.name}» выделена как отдельная core-позиция")
                break

    # 3. Check Sub-item disclosure
    # Check if items have included_sub_items
    items_with_sub = [it for it in items if len(it.included_sub_items) > 0]
    subitem_ratio = len(items_with_sub) / num_items
    if subitem_ratio >= 0.5:
        reasons_praise.append(f"Хорошее раскрытие подпозиций ({len(items_with_sub)}/{num_items})")
    elif len(items_with_sub) == 0:
        score -= 1.0
        reasons_penalty.append("Ни у одной категории не заполнено поле included_sub_items")

    # 4. Check that distinct markets are maintained
    # E.g. if expected_core_systems has 2 systems, did the extraction collapse everything into 1 single generic item or keep 2-4 focused categories?
    expected_systems = spec.get("expected_core_systems", [])
    if len(expected_systems) >= 2 and num_items == 1:
        # Check if the single item is a generic merge
        score -= 1.0
        reasons_penalty.append("Слишком сильное сжатие: разные рынки слиты в 1 позицию")

    # 5. Check reasonable category count
    if num_items > 8:
        score -= 1.5
        reasons_penalty.append(f"Чрезмерное дробление: {num_items} категорий для спецификации")

    final_score = max(1.0, min(10.0, round(score, 1)))

    return {
        "case_id": spec["id"],
        "industry": spec["industry"],
        "title": spec["title"],
        "score": final_score,
        "pass": final_score >= 8.0,
        "total_categories": num_items,
        "core_count": len(core_items),
        "aux_count": len(aux_items),
        "items_with_sub": len(items_with_sub),
        "reasons_penalty": reasons_penalty,
        "reasons_praise": reasons_praise,
        "categories": [
            {
                "id": it.id,
                "name": it.name,
                "is_core": it.is_core,
                "is_auxiliary": it.is_auxiliary,
                "cost_tier": it.cost_tier,
                "sub_items_count": len(it.included_sub_items),
                "sub_items_preview": list(it.included_sub_items)[:3],
            }
            for it in items
        ],
    }


async def run_crash_test():
    print("=" * 80)
    print("🚀 TENDERLEX: CRASH-TEST & DEEP EVALUATION ON 50 COMPLEX PROCUREMENTS")
    print(f"📦 Loaded {len(SPECIFICATIONS)} hard multi-item specifications across 10 industries.")
    print("=" * 80)

    session = next(db_session())
    settings = session.query(SystemSettings).first()
    if not settings or not settings.has_active_ai_provider:
        print("❌ Error: No active AI provider configured in SystemSettings.")
        sys.exit(1)

    print(f"🤖 AI Provider: {settings.primary_provider} | Model: {settings.primary_model}")
    print("⏳ Executing live profile extraction and clustering pipeline...")
    print("-" * 80)

    results = []
    start_time = time.time()

    for idx, spec in enumerate(SPECIFICATIONS, 1):
        case_id = spec["id"]
        industry = spec["industry"]
        title = spec["title"]
        print(f"[{idx:02d}/50] [{industry}] {title[:45]}...", end="", flush=True)

        t0 = time.time()
        try:
            profile = await build_procurement_profile(settings, spec["text"])
            dt = time.time() - t0
            evaluation = evaluate_case(spec, profile)
            evaluation["elapsed_sec"] = round(dt, 2)
            results.append(evaluation)

            status_icon = "✅" if evaluation["pass"] else "⚠️"
            print(f" {status_icon} {evaluation['score']}/10 ({dt:.1f}s | {evaluation['total_categories']} кат.)")
        except Exception as err:
            dt = time.time() - t0
            print(f" ❌ ERROR: {err} ({dt:.1f}s)")
            results.append({
                "case_id": case_id,
                "industry": industry,
                "title": title,
                "score": 0.0,
                "pass": False,
                "reasons_penalty": [f"Runtime error: {err}"],
                "categories": [],
                "total_categories": 0,
                "core_count": 0,
                "aux_count": 0,
                "items_with_sub": 0,
                "elapsed_sec": round(dt, 2),
            })

    total_duration = time.time() - start_time
    print("-" * 80)
    print(f"⏱️ Finished 50 crash-tests in {total_duration:.1f} seconds.")

    # Save complete JSON report
    report_path = Path("output/crash_test_50_results.json")
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(json.dumps(results, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"💾 Detailed results saved to: {report_path}")

    # Metrics computation
    total_cases = len(results)
    passed_cases = sum(1 for r in results if r["pass"])
    avg_score = sum(r["score"] for r in results) / total_cases if total_cases else 0.0
    total_categories = sum(r["total_categories"] for r in results)
    avg_categories = total_categories / total_cases if total_cases else 0.0
    avg_core = sum(r["core_count"] for r in results) / total_cases if total_cases else 0.0
    avg_aux = sum(r["aux_count"] for r in results) / total_cases if total_cases else 0.0
    total_subitems_items = sum(r["items_with_sub"] for r in results)

    # Industry breakdown
    industry_scores = {}
    for r in results:
        ind = r.get("industry", "Другое")
        industry_scores.setdefault(ind, []).append(r["score"])

    print("\n" + "=" * 80)
    print("📊 CRASH-TEST RESULTS SUMMARY & 10-POINT SCALE EVALUATION")
    print("=" * 80)
    print(f"Total Complex Cases Tested:            {total_cases}")
    print(f"Passed Threshold (Score >= 8.0):       {passed_cases}/{total_cases} ({passed_cases/total_cases*100:.1f}%)")
    print(f"Overall Quality Score (1-10 Scale):    {avg_score:.2f} / 10.0")
    print(f"Average Categories Extracted per Spec: {avg_categories:.1f}")
    print(f"Average Core Categories per Spec:      {avg_core:.1f}")
    print(f"Average Auxiliary Categories per Spec: {avg_aux:.1f}")
    print(f"Categories with Sub-Items Disclosed:   {total_subitems_items}/{total_categories} ({total_subitems_items/total_categories*100:.1f}%)")
    print("\n📈 Industry Breakdown:")
    for ind, sc_list in industry_scores.items():
        ind_avg = sum(sc_list) / len(sc_list)
        print(f"  • {ind:35s}: {ind_avg:.2f}/10 ({len(sc_list)} тестов)")

    print("=" * 80)

    return results


