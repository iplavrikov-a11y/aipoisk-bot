def write_editorial_material() -> None:
    text = """# Как сопоставить коммерческие предложения: проверяемая матрица по ТЗ

Коммерческие предложения удобно собирать в одном месте, но их нельзя честно сравнить одной строкой «цена». В одном ответе может быть указана поставка до склада, в другом — только сам товар. Один поставщик пишет срок для имеющегося остатка, другой — срок производства. Иногда модель, комплектация или условие гарантии остаются за пределами письма. Матрица нужна, чтобы увидеть эти различия до выбора, а не после подписания договора.

Этот материал — учебный алгоритм. Он не устанавливает цену, не заменяет проверку условий закупки и не говорит, какое предложение выбрать. Его задача — сохранить источник каждого утверждения и пометить неизвестное как неизвестное.

## Начните с строки требования, а не с названия товара

Перенесите из ТЗ каждую проверяемую характеристику в отдельную строку: назначение, материал, диапазон, присоединение, совместимость, количество, комплектность, документы и место поставки. Общий заголовок позиции почти никогда не достаточен. Например, учебная спецификация может содержать «насосный агрегат для перекачки воды». Для сравнения важны не только слова «насосный агрегат», но и производительность, напор, питание, исполнение, присоединение, комплект автоматики и условия эксплуатации.

Рядом с требованием оставьте колонку «источник подтверждения». В нее записывают не вывод сотрудника, а конкретный документ: паспорт изготовителя, каталог с номером версии, письмо поставщика, карточку товара или ответ на уточняющий вопрос. Ссылка без модели и даты часто не решает задачу: каталог мог быть обновлен, а в КП может быть другая комплектация.

## Используйте четыре статуса вместо догадки

Для каждого параметра достаточно четырех понятных состояний: «соответствует», «расхождение», «не подтверждено» и «нужно уточнение». «Соответствует» ставят, когда документ прямо подтверждает требование. «Расхождение» означает измеримое несовпадение. «Не подтверждено» — когда поставщик назвал модель или цену, но не прислал документ, из которого следует нужная характеристика. «Нужно уточнение» полезно, если формулировка ТЗ или ответа допускает несколько трактовок.

Не заменяйте «не подтверждено» предположением, что параметр стандартный. Особенно осторожно сравнивайте слова «не менее», «не более», «эквивалент», «совместимо» и «в комплекте». Их смысл определяется документацией и свойствами параметра. Если ответ меняет единицу измерения, материал, диапазон или состав комплекта, это следует отметить отдельно, даже когда общее название товара похоже.

## Сначала приведите условия поставки к одному виду

Цена из КП — это факт из документа, а не рыночная цена. В матрице не нужно придумывать условную стоимость для отсутствующего ответа. Запишите цену ровно так, как ее указал поставщик, и рядом отметьте НДС, валюту при необходимости, доставку, разгрузку, упаковку, тару и любые оговорки. Если доставка «по согласованию», ставьте «не подтверждено», а не ноль.

Также разнесите срок поставки и готовность комплекта. Поставщик может подтвердить наличие основного изделия, но не кабеля, крепежа, пускового комплекта или документации. В учебном примере один ответ содержит срок «две недели» и цену с НДС, но не указывает доставку и датчик в комплекте. Такой ответ не становится хуже автоматически: он требует вопроса. Второй ответ может быть дороже, но включать доставку и полный комплект. Матрица позволяет не потерять эту разницу.

## Проверьте происхождение каждого предложения

Запишите дату получения, срок действия КП, имя и рабочий контакт автора ответа. Если расчет используют для закупочного обоснования, сохраняйте исходное письмо и приложенный файл в той же папке, что и матрицу. При сомнении подтвердите у поставщика предмет, модель, дату и возможность поставить нужную комплектацию по контакту с официального сайта. Это проверка источника, а не обвинение в недостоверности.

Для первичной проверки реквизитов можно использовать государственные сервисы ФНС. Для закупок по 44-ФЗ метод определения и обоснования НМЦК задается статьей 22 закона; применимость конкретного метода и состав сведений зависят от предмета и актуальных правил. Матрица помогает организовать исходные данные, но не заменяет расчет, правовую оценку или решение заказчика.

## Рабочий порядок

1. Сохраните исходное ТЗ и присвойте версии спецификации понятное имя.
2. Отправьте одинаковый по содержанию запрос нескольким подходящим адресатам. Используйте DOCX-шаблон из этого набора как бланк, а не как готовый договор.
3. Заносите каждое КП в CSV-матрицу без преобразования исходной цены в «среднюю» или «рыночную».
4. Для каждого существенного параметра укажите источник и статус. Не закрывайте пустую ячейку предположением.
5. Сопоставьте полную конфигурацию, условия поставки, НДС, доставку, гарантию и срок действия предложения.
6. Сформируйте короткий список вопросов поставщику. После ответа добавьте дату и новый источник, не стирая первоначальную запись.
7. Перед выбором проверьте, что вывод основан на документах, а не только на названии модели или низкой цене.

Шаблон запроса и CSV — это отдельные рабочие бланки для КП. Они не являются отчетом по подбору товара и аналогов, не содержат ценовых ориентиров и не обещают результат закупки.

## Как читать заполненную матрицу

После заполнения не сортируйте строки только по числу в колонке «Цена из КП». Сначала отфильтруйте ответы, у которых существенные параметры остаются неподтвержденными или есть расхождение с ТЗ. Затем сравните оставшиеся варианты по полной конфигурации. Полезно вынести в отдельный список вопросы, которые меняют решение: включена ли доставка до нужного адреса, в каком виде передается товар, кто несет расходы на разгрузку, что считается началом гарантийного срока и когда заканчивается действие предложения.

Если условия нельзя привести к одному виду, матрица должна это показать. Не превращайте «доставка рассчитывается отдельно» в нулевую доставку и не складывайте разные комплектации как одинаковые позиции. В учебном бланке оставлены поля именно для таких различий. Для каждого уточнения сохраните дату, канал и документ. Это облегчает повторную проверку и объясняет, почему в итоговом сравнении была выбрана или исключена строка.

Матрица особенно полезна при обновлении ТЗ. Когда меняется хотя бы одно существенное требование, пометьте версию спецификации и повторно проверьте связанные ответы. Старое КП может остаться полезным источником контакта, но не обязательно относится к новой комплектации. Такой порядок помогает избежать ложной точности: таблица делает видимыми исходные данные и пробелы, но не заменяет ответственное решение закупщика.

## Источники для самостоятельной проверки

- [Федеральный закон № 44-ФЗ, официальный текст](https://pravo.gov.ru/proxy/ips/?docbody=&nd=102164547) — общая правовая рамка и статья 22; проверяйте действующую редакцию и специальные правила.
- [Единая информационная система в сфере закупок](https://zakupki.gov.ru/) — первичный источник извещений и документации конкретной закупки.
- [ФНС: сведения о юридических лицах](https://egrul.nalog.ru/index.html) — первичная проверка реквизитов контрагента; запись реестра не подтверждает возможность поставить товар.
"""
    (OUTPUT / "kak-sopostavit-kommercheskie-predlozheniya.md").write_text(text, encoding="utf-8")


def main() -> None:
    OUTPUT.mkdir(parents=True, exist_ok=True)
    write_request_template()
    write_matrix()
    write_editorial_material()


if __name__ == "__main__":
    main()
